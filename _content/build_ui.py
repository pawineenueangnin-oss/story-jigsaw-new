import json,importlib.util,sys
sys.path.insert(0,'_content/i18n')
from keys import K
from ui_th_es import TH,ES
LANGS=['th','en','es','zh','ja','ko','vi','id','ms','fil','hi','ar','fr','de','it','pt','ru','tr','pl','nl','uk']
NAMES={'th':'ไทย','en':'English','es':'Español','zh':'中文','ja':'日本語','ko':'한국어','vi':'Tiếng Việt','id':'Bahasa Indonesia','ms':'Bahasa Melayu','fil':'Filipino','hi':'हिन्दी','ar':'العربية','fr':'Français','de':'Deutsch','it':'Italiano','pt':'Português','ru':'Русский','tr':'Türkçe','pl':'Polski','nl':'Nederlands','uk':'Українська'}
SPEECH={'th':'th-TH','en':'en-US','es':'es-ES','zh':'zh-CN','ja':'ja-JP','ko':'ko-KR','vi':'vi-VN','id':'id-ID','ms':'ms-MY','fil':'fil-PH','hi':'hi-IN','ar':'ar-SA','fr':'fr-FR','de':'de-DE','it':'it-IT','pt':'pt-BR','ru':'ru-RU','tr':'tr-TR','pl':'pl-PL','nl':'nl-NL','uk':'uk-UA'}
T={'th':TH,'es':ES}
for lg in LANGS[3:]:
    m=importlib.import_module('ui_'+lg); assert len(m.UI)==len(K),lg
    T[lg]=dict(zip(K,m.UI))
from ui_extra import EXTRA
for lg,d in EXTRA.items(): T.setdefault(lg,{}).update(d)
for lg in T:
    for k,v in list(T[lg].items()):
        if k!=k.strip() and k.strip() not in T[lg]: T[lg][k.strip()]=v.strip()
import re as _re
LRI,PDI='\u2066','\u2069'
for k,v in list(T['ar'].items()):
    v=_re.sub(r'\{0\} / \{1\}|\{0\}–\{1\}|\{0\} × \{1\}|★★★ ≤ \{0\}|★★ ≤ \{1\}',lambda m:LRI+m.group(0)+PDI,v); T['ar'][k]=v
out='/* generated by _content/build_ui.py */\nwindow.I18N_LANGS='+json.dumps(LANGS)+';\nwindow.I18N_NAMES='+json.dumps(NAMES,ensure_ascii=False)+';\nwindow.I18N_SPEECH='+json.dumps(SPEECH)+';\nwindow.I18N_KEYS='+json.dumps(K,ensure_ascii=False)+';\nwindow.I18N_UI='+json.dumps(T,ensure_ascii=False,separators=(',',':'))+';\n'
open('i18n/ui.js','w').write(out); print(len(out))
