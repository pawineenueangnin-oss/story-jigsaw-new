# Generates sw.js with a precache list of every game asset and a content-hash version.
import os,hashlib,json
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
skip_dirs={'.git','_content','_review','_shots','node_modules','.github'}
exts={'.html','.js','.css','.webp','.png','.jpg','.jpeg','.ico','.webmanifest','.json','.mp3','.ogg','.svg','.woff2'}
files=[]
for d,ds,fs in os.walk(root):
    ds[:]=sorted(x for x in ds if x not in skip_dirs and not x.startswith('.'))
    for f in sorted(fs):
        if f=='sw.js' or os.path.splitext(f)[1].lower() not in exts:continue
        files.append(os.path.relpath(os.path.join(d,f),root).replace(os.sep,'/'))
h=hashlib.sha256()
for f in files:
    h.update(f.encode());h.update(open(os.path.join(root,f),'rb').read())
h.update(open(__file__,'rb').read())  # sw logic changes also bump the version
ver=h.hexdigest()[:12]
assets=['./']+files
sw=f"""// Generated by _content/build_sw.py — do not edit by hand.
const VERSION='sjt-{ver}';
const ASSETS={json.dumps(assets,ensure_ascii=False)};
self.addEventListener('message',e=>{{if(e.data==='skipWaiting')self.skipWaiting();}});
self.addEventListener('install',e=>{{e.waitUntil(caches.open(VERSION).then(c=>Promise.all(ASSETS.map(u=>c.add(new Request(u,{{cache:'reload'}})).catch(()=>{{}})))).then(()=>self.skipWaiting()));}});
self.addEventListener('activate',e=>{{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k.startsWith('sjt-')&&k!==VERSION).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));}});
self.addEventListener('fetch',e=>{{
 const r=e.request;if(r.method!=='GET')return;const u=new URL(r.url);if(u.origin!==location.origin)return;
 if(r.mode==='navigate'){{e.respondWith(fetch(new Request(r.url,{{cache:'no-cache',credentials:'same-origin'}})).then(res=>{{const c=res.clone();caches.open(VERSION).then(x=>x.put(u.pathname.endsWith('/')?'./':r,c));return res;}}).catch(()=>caches.open(VERSION).then(c=>c.match(r,{{ignoreSearch:true}}).then(m=>m||c.match('./')))));return;}}
 e.respondWith(caches.open(VERSION).then(c=>c.match(r,{{ignoreSearch:true}})).then(m=>m||fetch(r).then(res=>{{if(res.ok){{const c=res.clone();caches.open(VERSION).then(x=>x.put(r,c));}}return res;}})));
}});
"""
open(os.path.join(root,'sw.js'),'w').write(sw)
print(ver,len(assets),'assets')
